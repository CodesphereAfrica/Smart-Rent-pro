<?php
// modules/announcements/view.php — read-only detail of a single announcement.
declare(strict_types=1);

require_once __DIR__ . '/../../includes/auth.php';
require_once __DIR__ . '/../../includes/functions.php';

$USER = require_permission('communications.view');
$cid  = (int)$USER['company_id'];

$id = (int)($_GET['id'] ?? 0);

$a = db_one(
    'SELECT a.*,
            p.name AS property_name, p.id AS property_id,
            CONCAT(u.first_name, " ", u.last_name) AS creator_name,
            u.email AS creator_email
       FROM announcements a
       LEFT JOIN properties p ON p.id = a.property_id
       LEFT JOIN users u      ON u.id = a.created_by
      WHERE a.id = :id AND a.company_id = :c
      LIMIT 1',
    [':id' => $id, ':c' => $cid]
);

if (!$a) {
    flash_error(__('Announcement not found.'));
    redirect('modules/announcements/index.php');
}

// ---------------------------------------------------------------------------
// Derive a display status from the timestamps — there's no status column.
// ---------------------------------------------------------------------------
$now = time();
$publishedTs = $a['published_at'] ? strtotime($a['published_at']) : null;
$expiresTs   = $a['expires_at']   ? strtotime($a['expires_at'])   : null;

if ($publishedTs === null || $publishedTs > $now) {
    $status = 'scheduled';
    $statusClass = 'badge-status-reserved';
    $statusLabel = __('Scheduled');
} elseif ($expiresTs !== null && $expiresTs < $now) {
    $status = 'expired';
    $statusClass = 'badge-status-unavailable';
    $statusLabel = __('Expired');
} else {
    $status = 'published';
    $statusClass = 'badge-status-available';
    $statusLabel = __('Published');
}

// ---------------------------------------------------------------------------
// Delivery stats: how many in-app notifications were generated by this announcement.
// ---------------------------------------------------------------------------
$notifStats = db_one(
    'SELECT COUNT(*) AS total,
            SUM(is_read = 1) AS read_count
       FROM notifications
      WHERE related_type = "announcement" AND related_id = :id',
    [':id' => $id]
);
$notifTotal = (int)($notifStats['total'] ?? 0);
$notifRead  = (int)($notifStats['read_count'] ?? 0);
$readPct    = $notifTotal > 0 ? round(($notifRead / $notifTotal) * 100) : 0;

// Audience human label
$audienceLabels = [
    'all'     => __('Everyone'),
    'tenants' => __('Tenants'),
    'owners'  => __('Owners'),
    'staff'   => __('Staff'),
];
$audienceLabel = $audienceLabels[$a['audience']] ?? ucfirst((string)$a['audience']);

$PAGE_TITLE = $a['title'];
require __DIR__ . '/../../includes/header.php';
?>

<nav aria-label="breadcrumb"><ol class="breadcrumb small">
  <li class="breadcrumb-item"><a href="<?= APP_URL ?>/modules/announcements/index.php"><?= e(__('Announcements')) ?></a></li>
  <li class="breadcrumb-item active"><?= e($a['title']) ?></li>
</ol></nav>

<div class="d-flex flex-wrap justify-content-between align-items-start gap-3 mb-3">
  <div class="flex-grow-1">
    <h1 class="h4 mb-1"><?= e($a['title']) ?></h1>
    <div class="text-muted small d-flex flex-wrap align-items-center gap-2">
      <span class="srp-badge-pill <?= e($statusClass) ?>">
        <span class="dot"></span><?= e($statusLabel) ?>
      </span>
      <span><i data-lucide="users" style="width:13px;height:13px"></i> <?= e($audienceLabel) ?></span>
      <?php if ($a['property_name']): ?>
        <span><i data-lucide="building" style="width:13px;height:13px"></i> <?= e($a['property_name']) ?></span>
      <?php else: ?>
        <span><i data-lucide="building-2" style="width:13px;height:13px"></i> <?= e(__('Company-wide')) ?></span>
      <?php endif; ?>
    </div>
  </div>
  <div class="d-flex gap-2 flex-wrap">
    <?php if (can('communications.send')): ?>
      <a class="btn btn-light" href="<?= APP_URL ?>/modules/announcements/edit.php?id=<?= (int)$id ?>">
        <i data-lucide="pencil"></i> <?= e(__('Edit')) ?>
      </a>
      <a class="btn btn-light text-danger" href="<?= APP_URL ?>/modules/announcements/delete.php?id=<?= (int)$id ?>">
        <i data-lucide="trash-2"></i> <?= e(__('Delete')) ?>
      </a>
    <?php endif; ?>
  </div>
</div>

<div class="row g-3">
  <div class="col-lg-8">
    <div class="srp-card p-4 mb-3">
      <div class="announcement-body" style="line-height: 1.65; font-size: 15px;">
        <?= nl2br(e($a['body'])) ?>
      </div>
    </div>

    <div class="srp-card p-4">
      <h2 class="h6 mb-3"><?= e(__('Timeline')) ?></h2>
      <ul class="list-unstyled small mb-0">
        <li class="border-bottom py-2 d-flex justify-content-between">
          <span class="text-muted"><?= e(__('Created')) ?></span>
          <span><?= e(date('Y-m-d H:i', strtotime($a['created_at']))) ?></span>
        </li>
        <?php if ($a['published_at']): ?>
          <li class="border-bottom py-2 d-flex justify-content-between">
            <span class="text-muted"><?= e(__('Published')) ?></span>
            <span><?= e(date('Y-m-d H:i', strtotime($a['published_at']))) ?></span>
          </li>
        <?php endif; ?>
        <?php if ($a['expires_at']): ?>
          <li class="py-2 d-flex justify-content-between">
            <span class="text-muted"><?= e(__('Expires')) ?></span>
            <span><?= e(date('Y-m-d H:i', strtotime($a['expires_at']))) ?></span>
          </li>
        <?php endif; ?>
      </ul>
    </div>
  </div>

  <div class="col-lg-4">
    <div class="srp-card p-4 mb-3">
      <h2 class="h6 mb-3"><?= e(__('Author')) ?></h2>
      <div class="small">
        <div class="fw-semibold"><?= e($a['creator_name'] ?? '—') ?></div>
        <?php if ($a['creator_email']): ?>
          <div class="text-muted"><?= e($a['creator_email']) ?></div>
        <?php endif; ?>
      </div>
    </div>

    <?php if ($notifTotal > 0): ?>
      <div class="srp-card p-4 mb-3">
        <h2 class="h6 mb-3"><?= e(__('In-App Delivery')) ?></h2>
        <div class="d-flex justify-content-between mb-2">
          <span class="text-muted small"><?= e(__('Notified')) ?></span>
          <span class="fw-semibold"><?= $notifTotal ?></span>
        </div>
        <div class="d-flex justify-content-between mb-2">
          <span class="text-muted small"><?= e(__('Read')) ?></span>
          <span class="fw-semibold"><?= $notifRead ?> (<?= $readPct ?>%)</span>
        </div>
        <div class="progress" style="height:6px">
          <div class="progress-bar" role="progressbar" style="width: <?= $readPct ?>%"></div>
        </div>
      </div>
    <?php endif; ?>

    <div class="srp-card p-4">
      <h2 class="h6 mb-3"><?= e(__('Scope')) ?></h2>
      <div class="small">
        <div class="mb-2">
          <span class="text-muted"><?= e(__('Audience')) ?>:</span>
          <span><?= e($audienceLabel) ?></span>
        </div>
        <div>
          <span class="text-muted"><?= e(__('Property')) ?>:</span>
          <?php if ($a['property_name']): ?>
            <a href="<?= APP_URL ?>/modules/properties/view.php?id=<?= (int)$a['property_id'] ?>" class="text-decoration-none"><?= e($a['property_name']) ?></a>
          <?php else: ?>
            <span><?= e(__('Company-wide')) ?></span>
          <?php endif; ?>
        </div>
      </div>
    </div>
  </div>
</div>

<?php require __DIR__ . '/../../includes/footer.php'; ?>