<?php
// modules/reports/export-excel.php — stream a cached report as .xlsx via PhpSpreadsheet.
declare(strict_types=1);

require_once __DIR__ . '/../../includes/auth.php';
require_once __DIR__ . '/../../includes/functions.php';
require_once __DIR__ . '/_export.php';
require_once __DIR__ . '/../../vendor/autoload.php';

$USER = require_permission('reports.export');

$key = preg_replace('/[^a-z0-9_\-]/i', '', (string)($_GET['key'] ?? ''));
if ($key === '') {
    http_response_code(400);
    exit('Missing key');
}

$cached = report_cached($key);
if (!$cached) {
    http_response_code(404);
    exit('Report cache expired — open the report again and click Export.');
}

$title   = (string)$cached['title'];
$headers = (array)$cached['headers'];
$rows    = (array)$cached['rows'];
$filters = (array)($cached['filters'] ?? []);

$spreadsheet = new \PhpOffice\PhpSpreadsheet\Spreadsheet();

// -------- Sheet 1: the report body --------
$sheet = $spreadsheet->getActiveSheet();
$sheet->setTitle(substr(preg_replace('/[^A-Za-z0-9 _\-]/', '', $title) ?: 'Report', 0, 31));

// Title banner
$sheet->setCellValue('A1', $title);
$sheet->mergeCells('A1:' . \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex(count($headers)) . '1');
$sheet->getStyle('A1')->getFont()->setBold(true)->setSize(14);
$sheet->getStyle('A1')->getAlignment()->setHorizontal(\PhpOffice\PhpSpreadsheet\Style\Alignment::HORIZONTAL_CENTER);

// Filters row
$filterLine = 'Period: ' . ($filters['from'] ?? '') . ' → ' . ($filters['to'] ?? '');
if (!empty($filters['property_id'])) {
    $pname = db_one('SELECT name FROM properties WHERE id = :p', [':p' => (int)$filters['property_id']]);
    if ($pname) $filterLine .= ' · Property: ' . $pname['name'];
}
$sheet->setCellValue('A2', $filterLine);
$sheet->mergeCells('A2:' . \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex(count($headers)) . '2');
$sheet->getStyle('A2')->getFont()->setItalic(true)->getColor()->setRGB('64748b');

// Header row at row 4
$headerRow = 4;
$colIdx = 1;
foreach ($headers as $h) {
    $colLetter = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($colIdx);
    $sheet->setCellValue($colLetter . $headerRow, (string)$h);
    $colIdx++;
}
$lastColLetter = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex(count($headers));
$sheet->getStyle('A' . $headerRow . ':' . $lastColLetter . $headerRow)->applyFromArray([
    'font' => ['bold' => true, 'color' => ['rgb' => '64748b']],
    'fill' => [
        'fillType' => \PhpOffice\PhpSpreadsheet\Style\Fill::FILL_SOLID,
        'startColor' => ['rgb' => 'f6f7fb'],
    ],
]);

// Data rows
$rowIdx = $headerRow + 1;
foreach ($rows as $r) {
    $colIdx = 1;
    foreach ((array)$r as $v) {
        $colLetter = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($colIdx);
        $sheet->setCellValueExplicit(
            $colLetter . $rowIdx,
            (string)$v,
            \PhpOffice\PhpSpreadsheet\Cell\DataType::TYPE_STRING
        );
        $colIdx++;
    }
    $rowIdx++;
}

// Auto widths
$colIdx = 1;
foreach ($headers as $_h) {
    $colLetter = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($colIdx);
    $sheet->getColumnDimension($colLetter)->setAutoSize(true);
    $colIdx++;
}

// Freeze header
$sheet->freezePane('A' . ($headerRow + 1));

// -------- Sheet 2: metadata --------
$meta = $spreadsheet->createSheet();
$meta->setTitle('Metadata');
$meta->setCellValue('A1', 'Report');
$meta->setCellValue('B1', $title);
$meta->setCellValue('A2', 'Generated By');
$meta->setCellValue('B2', trim(($USER['first_name'] ?? '') . ' ' . ($USER['last_name'] ?? '')));
$meta->setCellValue('A3', 'Generated At');
$meta->setCellValue('B3', date('Y-m-d H:i:s'));
$meta->setCellValue('A4', 'Period');
$meta->setCellValue('B4', ($filters['from'] ?? '') . ' → ' . ($filters['to'] ?? ''));
$meta->setCellValue('A5', 'Company');
$company = db_one('SELECT name FROM companies WHERE id = :c', [':c' => (int)$USER['company_id']]);
$meta->setCellValue('B5', $company['name'] ?? '');
$meta->setCellValue('A6', 'Row Count');
$meta->setCellValue('B6', count($rows));
$meta->getColumnDimension('A')->setAutoSize(true);
$meta->getColumnDimension('B')->setAutoSize(true);
$meta->getStyle('A1:A6')->getFont()->setBold(true);

// -------- Stream --------
$filename = preg_replace('/[^A-Za-z0-9_\-]/', '_', $title) . '-' . date('Ymd-Hi') . '.xlsx';

header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Cache-Control: max-age=0');

$writer = new \PhpOffice\PhpSpreadsheet\Writer\Xlsx($spreadsheet);
$writer->save('php://output');

log_audit('reports', 'export_excel', null, null, null, ['key' => $key, 'rows' => count($rows)]);
exit;